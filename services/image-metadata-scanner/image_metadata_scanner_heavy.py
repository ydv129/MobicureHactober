@app.post("/api/scan")
async def scan_image(file: UploadFile = File(...)) -> JSONResponse:
    if not file.filename:
        raise HTTPException(status_code=400, detail="No file provided")

    suffix = (file.filename.rsplit(".", 1)[-1] if "." in file.filename else "").lower()
    ext = f".{suffix}" if suffix else ""
    if ext not in ALLOWED_EXTENSIONS:
        raise HTTPException(status_code=400, detail="Unsupported file type")

    content = await file.read()
    if len(content) > MAX_UPLOAD_BYTES:
        raise HTTPException(status_code=413, detail="File too large")

    try:
        image = Image.open(io.BytesIO(content))
        image.verify()  # Verify image integrity
    except (UnidentifiedImageError, Exception) as e:
        raise HTTPException(status_code=400, detail="Invalid or corrupted image file")

    # Re-open for processing (verify() closes the image)
    image = Image.open(io.BytesIO(content))

    try:
        analysis_bundle = _analyze_pipeline(image, content)
    except Exception as e:
        # Log the error and return a safe response
        import traceback
        traceback.print_exc()
        raise HTTPException(status_code=500, detail=f"Analysis error: {str(e)}")

    scan_id = str(uuid.uuid4())
    result = {
        "scan_id": scan_id,
        "filename": file.filename,
        "file_size": len(content),
        "file_hash": _sha256_bytes(content),
        "created_at": _now_iso(),
        **analysis_bundle,
    }

    SCAN_RESULTS[scan_id] = {"result": result, "created_at": time.time()}
    return JSONResponse({"scan_id": scan_id, "status": "completed", "results": result})


