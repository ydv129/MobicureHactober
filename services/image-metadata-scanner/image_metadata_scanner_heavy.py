def _detect_blending_artifacts(img: np.ndarray, x1: int, y1: int, x2: int, y2: int) -> float:
    """Detect blending artifacts at face boundaries (common in face swaps)."""
    h, w = img.shape[:2]
    
    # Create boundary mask
    boundary_width = max(3, int((x2 - x1) * 0.08))
    
    scores = []
    
    # Check each boundary
    # Top boundary
    if y1 > boundary_width:
        inside = img[y1:y1+boundary_width, x1:x2].astype(np.float32)
        outside = img[y1-boundary_width:y1, x1:x2].astype(np.float32)
        if inside.size > 0 and outside.size > 0:
            diff = np.abs(np.mean(inside, axis=(0,1)) - np.mean(outside, axis=(0,1)))
            gradient_inside = np.std(inside)
            gradient_outside = np.std(outside)
            gradient_diff = abs(gradient_inside - gradient_outside) / (gradient_inside + gradient_outside + 1e-6)
            scores.append(np.mean(diff) / 255 + gradient_diff * 0.5)
    
    # Bottom boundary
    if y2 < h - boundary_width:
        inside = img[y2-boundary_width:y2, x1:x2].astype(np.float32)
        outside = img[y2:y2+boundary_width, x1:x2].astype(np.float32)
        if inside.size > 0 and outside.size > 0:
            diff = np.abs(np.mean(inside, axis=(0,1)) - np.mean(outside, axis=(0,1)))
            gradient_inside = np.std(inside)
            gradient_outside = np.std(outside)
            gradient_diff = abs(gradient_inside - gradient_outside) / (gradient_inside + gradient_outside + 1e-6)
            scores.append(np.mean(diff) / 255 + gradient_diff * 0.5)
    
    # Left boundary
    if x1 > boundary_width:
        inside = img[y1:y2, x1:x1+boundary_width].astype(np.float32)
        outside = img[y1:y2, x1-boundary_width:x1].astype(np.float32)
        if inside.size > 0 and outside.size > 0:
            diff = np.abs(np.mean(inside, axis=(0,1)) - np.mean(outside, axis=(0,1)))
            scores.append(np.mean(diff) / 255)
    
    # Right boundary
    if x2 < w - boundary_width:
        inside = img[y1:y2, x2-boundary_width:x2].astype(np.float32)
        outside = img[y1:y2, x2:x2+boundary_width].astype(np.float32)
        if inside.size > 0 and outside.size > 0:
            diff = np.abs(np.mean(inside, axis=(0,1)) - np.mean(outside, axis=(0,1)))
            scores.append(np.mean(diff) / 255)
    
    return np.mean(scores) if scores else 0.0


def _detect_frequency_artifacts(face_img: np.ndarray) -> float:
    """Detect GAN-specific frequency artifacts using FFT analysis."""
    if face_img.size == 0:
        return 0.0
    
    # Convert to grayscale
    if len(face_img.shape) == 3:
        gray = np.mean(face_img, axis=2)
    else:
        gray = face_img
    
    # Resize for consistent analysis
    target_size = 128
    if gray.shape[0] != target_size or gray.shape[1] != target_size:
        from PIL import Image as PILImage
        gray_pil = PILImage.fromarray(gray.astype(np.uint8))
        gray_pil = gray_pil.resize((target_size, target_size), PILImage.Resampling.BILINEAR)
        gray = np.array(gray_pil, dtype=np.float32)
    
    # FFT analysis
    fft = np.fft.fft2(gray)
    fft_shift = np.fft.fftshift(fft)
    magnitude = np.abs(fft_shift)
    
    # Normalize
    magnitude = np.log1p(magnitude)
    magnitude = magnitude / (np.max(magnitude) + 1e-6)
    
    # Check for periodic patterns (GAN artifacts often show grid-like patterns)
    center = target_size // 2
    
    # Analyze specific frequencies where GAN artifacts appear
    artifact_score = 0
    
    # Check for checkerboard artifacts (common in upsampling)
    high_freq_region = magnitude[center-10:center+10, center-10:center+10]
    corners = [
        magnitude[:20, :20],
        magnitude[:20, -20:],
        magnitude[-20:, :20],
        magnitude[-20:, -20:]
    ]
    
    corner_energy = np.mean([np.mean(c) for c in corners])
    center_energy = np.mean(high_freq_region)
    
    # GAN images often have unusual high-frequency patterns
    if corner_energy > center_energy * 0.8:
        artifact_score += 0.3
    
    # Check for periodic spikes
    threshold = np.mean(magnitude) + 2 * np.std(magnitude)
    spikes = np.sum(magnitude > threshold)
    spike_ratio = spikes / magnitude.size
    
    if spike_ratio > 0.01 and spike_ratio < 0.05:
        artifact_score += 0.3
    
    # Radial frequency analysis
    y, x = np.ogrid[:target_size, :target_size]
    r = np.sqrt((x - center)**2 + (y - center)**2)
    
    # Check frequency distribution smoothness
    radial_bins = 20
    radial_profile = []
    for i in range(radial_bins):
        r_min, r_max = i * center / radial_bins, (i+1) * center / radial_bins
        mask = (r >= r_min) & (r < r_max)
        if np.any(mask):
            radial_profile.append(np.mean(magnitude[mask]))
    
    if len(radial_profile) > 5:
        profile_gradient = np.gradient(radial_profile)
        irregularity = np.std(profile_gradient) / (np.mean(np.abs(profile_gradient)) + 1e-6)
        if irregularity > 1.5:
            artifact_score += 0.2
    
    return min(1.0, artifact_score)


def _check_color_consistency(img: np.ndarray, x1: int, y1: int, x2: int, y2: int) -> float:
    """Check color consistency between face region and surrounding area."""
    h, w = img.shape[:2]
    
    face_region = img[y1:y2, x1:x2].astype(np.float32)
    
    # Get surrounding region
    pad = max(20, int((x2 - x1) * 0.3))
    sy1, sy2 = max(0, y1-pad), min(h, y2+pad)
    sx1, sx2 = max(0, x1-pad), min(w, x2+pad)
    
    # Create mask for surrounding area (excluding face)
    surrounding = img[sy1:sy2, sx1:sx2].astype(np.float32)
    
    if face_region.size == 0 or surrounding.size == 0:
        return 0.0
    
    # Compare color distributions
    scores = []
    for c in range(3):
        face_hist, _ = np.histogram(face_region[:,:,c].flatten(), bins=32, range=(0, 256))
        surr_hist, _ = np.histogram(surrounding[:,:,c].flatten(), bins=32, range=(0, 256))
        
        # Normalize histograms
        face_hist = face_hist / (face_hist.sum() + 1e-6)
        surr_hist = surr_hist / (surr_hist.sum() + 1e-6)
        
        # Chi-square distance
        chi_sq = np.sum((face_hist - surr_hist)**2 / (face_hist + surr_hist + 1e-6))
        scores.append(chi_sq)
    
    # Also check white balance consistency
    face_wb = np.mean(face_region, axis=(0,1))
    surr_wb = np.mean(surrounding, axis=(0,1))
    wb_diff = np.abs(face_wb - surr_wb) / 255
    
    color_score = np.mean(scores) / 2 + np.mean(wb_diff)
    
    return min(1.0, color_score)


def _analyze_skin_texture(face_img: np.ndarray) -> float:
    """Analyze skin texture for synthetic patterns."""
    if face_img.size == 0 or face_img.shape[0] < 20 or face_img.shape[1] < 20:
        return 0.0
    
    # Convert to grayscale
    if len(face_img.shape) == 3:
        gray = np.mean(face_img, axis=2).astype(np.float32)
    else:
        gray = face_img.astype(np.float32)
    
    # High-pass filter to extract texture
    from PIL import Image as PILImage, ImageFilter
    gray_pil = PILImage.fromarray(gray.astype(np.uint8))
    blurred = gray_pil.filter(ImageFilter.GaussianBlur(radius=2))
    texture = np.abs(gray - np.array(blurred, dtype=np.float32))
    
    # Analyze texture statistics
    texture_mean = np.mean(texture)
    texture_std = np.std(texture)
    
    # Real skin has specific texture characteristics
    # Synthetic skin often has too uniform or too regular texture
    
    # Check texture uniformity
    h, w = texture.shape
    block_size = max(10, min(h, w) // 4)
    block_stds = []
    
    for y in range(0, h - block_size, block_size):
        for x in range(0, w - block_size, block_size):
            block = texture[y:y+block_size, x:x+block_size]
            block_stds.append(np.std(block))
    
    if block_stds:
        std_of_stds = np.std(block_stds)
        mean_of_stds = np.mean(block_stds)
        
        # Too uniform texture is suspicious
        uniformity = std_of_stds / (mean_of_stds + 1e-6)
        
        if uniformity < 0.3:
            return 0.6  # Very uniform - suspicious
        elif uniformity < 0.5:
            return 0.3  # Somewhat uniform
    
    # Check for repetitive patterns
    if texture_std < 3:
        return 0.5  # Very smooth - might be synthetic
    
    return 0.0


def _check_landmark_consistency(face_img: np.ndarray, landmarks: np.ndarray, offset: Tuple[int, int]) -> float:
    """Check facial landmark consistency for manipulation detection."""
    if landmarks is None or len(landmarks) < 5:
        return 0.0
    
    # Adjust landmarks to face region coordinates
    adjusted_landmarks = landmarks - np.array(offset)
    
    # Check landmark symmetry (faces should be roughly symmetric)
    # Assuming 5-point landmarks: left_eye, right_eye, nose, left_mouth, right_mouth
    if len(adjusted_landmarks) >= 5:
        left_eye = adjusted_landmarks[0]
        right_eye = adjusted_landmarks[1]
        nose = adjusted_landmarks[2]
        
        # Check eye alignment
        eye_angle = np.arctan2(right_eye[1] - left_eye[1], right_eye[0] - left_eye[0])
        
        # Check if nose is centered between eyes
        eye_center = (left_eye + right_eye) / 2
        nose_offset = abs(nose[0] - eye_center[0]) / (abs(right_eye[0] - left_eye[0]) + 1e-6)
        
        # Manipulated faces often have misaligned features
        score = 0.0
        
        if abs(eye_angle) > 0.15:  # More than ~8.5 degrees
            score += 0.2
        
        if nose_offset > 0.15:
            score += 0.2
        
        # Check proportions
        eye_distance = np.linalg.norm(right_eye - left_eye)
        eye_nose_distance = np.linalg.norm(nose - eye_center)
        
        # Typical ratio is around 0.7-1.0
        ratio = eye_nose_distance / (eye_distance + 1e-6)
        if ratio < 0.5 or ratio > 1.3:
            score += 0.3
        
        return min(1.0, score)
    
    return 0.0


def _check_face_compression(face_img: np.ndarray, full_img: np.ndarray, 
                            x1: int, y1: int, x2: int, y2: int) -> float:
    """Check for compression inconsistencies between face and background."""
    if face_img.size == 0:
        return 0.0
    
    # Convert to grayscale
    if len(face_img.shape) == 3:
        face_gray = np.mean(face_img, axis=2)
    else:
        face_gray = face_img
    
    if len(full_img.shape) == 3:
        full_gray = np.mean(full_img, axis=2)
    else:
        full_gray = full_img
    
    # Analyze 8x8 block artifacts (JPEG compression)
    def get_block_artifact_score(img):
        h, w = img.shape
        if h < 16 or w < 16:
            return 0
        
        # Check boundaries at 8-pixel intervals
        h_boundaries = []
        for y in range(8, h-8, 8):
            diff = np.abs(img[y-1, :] - img[y, :])
            h_boundaries.append(np.mean(diff))
        
        v_boundaries = []
        for x in range(8, w-8, 8):
            diff = np.abs(img[:, x-1] - img[:, x])
            v_boundaries.append(np.mean(diff))
        
        return np.mean(h_boundaries + v_boundaries) if (h_boundaries or v_boundaries) else 0
    
    face_compression = get_block_artifact_score(face_gray.astype(np.float32))
    
    # Get background region
    h, w = full_gray.shape
    pad = 50
    bg_regions = []
    
    # Sample background regions
    if y1 > pad:
        bg_regions.append(full_gray[:y1-10, :])
    if y2 < h - pad:
        bg_regions.append(full_gray[y2+10:, :])
    
    if bg_regions:
        bg_scores = [get_block_artifact_score(bg.astype(np.float32)) for bg in bg_regions if bg.size > 100]
        if bg_scores:
            bg_compression = np.mean(bg_scores)
            
            # Significant difference indicates manipulation
            diff = abs(face_compression - bg_compression)
            normalized_diff = diff / (max(face_compression, bg_compression) + 1e-6)
            
            if normalized_diff > 0.5:
                return 0.7
            elif normalized_diff > 0.3:
                return 0.4
    
    return 0.0


