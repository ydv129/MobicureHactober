def _is_service_running() -> Optional[int]:
    """Check if service is running and return PID."""
    if not PID_FILE.exists():
        return None
    
    try:
        pid = int(PID_FILE.read_text().strip())
        # Check if process exists
        os.kill(pid, 0)
        return pid
    except (ProcessLookupError, ValueError):
        # Process doesn't exist, clean up stale PID file
        PID_FILE.unlink(missing_ok=True)
        return None


def _start_service(host: str, port: int) -> None:
    """Start service as background daemon."""
    pid = _is_service_running()
    if pid:
        print(f"Service already running (PID: {pid})")
        print(f"Access at: http://localhost:{port}")
        return
    
    print(f"Starting {APP_NAME}...")
    
    # Start as background process
    cmd = [
        sys.executable,
        str(Path(__file__).absolute()),
        "--host", host,
        "--port", str(port)
    ]
    
    # Open log file
    log_fd = open(LOG_FILE, "a")
    
    # Start subprocess
    process = subprocess.Popen(
        cmd,
        stdout=log_fd,
        stderr=log_fd,
        start_new_session=True
    )
    
    # Save PID
    PID_FILE.write_text(str(process.pid))
    
    print(f"Service started (PID: {process.pid})")
    print(f"Access at: http://localhost:{port}")
    print(f"📋 Logs: {LOG_FILE}")
    
    # Wait a moment and verify it's still running
    time.sleep(2)
    if not _is_service_running():
        print("Service failed to start. Check logs:")
        print(f"   tail -n 20 {LOG_FILE}")
        sys.exit(1)
    
    print("Service is healthy")


def _stop_service() -> None:
    """Stop running service."""
    pid = _is_service_running()
    if not pid:
        print("Service is not running")
        return
    
    print(f"🛑 Stopping service (PID: {pid})...")
    
    try:
        # Try graceful shutdown
        os.kill(pid, signal.SIGTERM)
        
        # Wait up to 5 seconds for graceful shutdown
        for _ in range(10):
            time.sleep(0.5)
            if not _is_service_running():
                break
        else:
            # Force kill if still running
            print("Forcing shutdown...")
            os.kill(pid, signal.SIGKILL)
            time.sleep(0.5)
        
        PID_FILE.unlink(missing_ok=True)
        print("Service stopped")
        
    except ProcessLookupError:
        print("Process not found")
        PID_FILE.unlink(missing_ok=True)
    except Exception as e:
        print(f"Error stopping service: {e}")
        sys.exit(1)


def _restart_service(host: str, port: int) -> None:
    """Restart service."""
    print("🔄 Restarting service...")
    _stop_service()
    time.sleep(1)
    _start_service(host, port)


def _check_status() -> None:
    """Check service status."""
    pid = _is_service_running()
    if pid:
        print(f"Service is running (PID: {pid})")
        print(f"Access at: http://localhost:{SERVICE_PORT}")
        print(f"📋 Logs: {LOG_FILE}")
    else:
        print("Service is not running")
        sys.exit(1)


def _cleanup_on_exit():
    """Cleanup handler for graceful shutdown."""
    PID_FILE.unlink(missing_ok=True)


def _run_cli() -> None:
    args = _parse_cli_args()
    
    # Handle daemon commands
    if args.start:
        _start_service(args.host, args.port)
        return
    
    if args.stop:
        _stop_service()
        return
    
    if args.restart:
        _restart_service(args.host, args.port)
        return
    
    if args.status:
        _check_status()
        return
    
    if args.self_test:
        _run_self_test()
        return
    
    # Normal server mode (foreground)
    # Register cleanup handler
    atexit.register(_cleanup_on_exit)
    
    # Save PID for foreground mode too
    PID_FILE.write_text(str(os.getpid()))
    
    logger.info(f"Starting {APP_NAME} v{APP_VERSION}")
    logger.info(f"Server running at http://{args.host}:{args.port}")
    logger.info(f"📡 API endpoint: http://{args.host}:{args.port}/api/scan")
    logger.info(f"🏥 Health check: http://{args.host}:{args.port}/health")
    
    try:
        uvicorn.run(app, host=args.host, port=args.port, log_level="info")
    finally:
        _cleanup_on_exit()


if __name__ == "__main__":
    _run_cli()
